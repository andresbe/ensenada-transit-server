const {test}=require('node:test');const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');const {PGlite}=require('@electric-sql/pglite');
process.env.NODE_ENV='test';
test('start retries return the original session and never replace another active service',async t=>{
 const pg=new PGlite();t.after(()=>pg.close());
 await pg.exec(`CREATE TABLE users(id uuid,role text,status text);
 CREATE TABLE conductores(id uuid PRIMARY KEY,correo text);
 CREATE TABLE routes(id uuid PRIMARY KEY,transport_line_id uuid,active boolean DEFAULT true,checkpoint_revision int DEFAULT 0);
 CREATE TABLE route_variants(id uuid PRIMARY KEY,route_id uuid,direction text,coordinates jsonb);
 CREATE TABLE driver_checkpoint_runs(id uuid DEFAULT gen_random_uuid(),session_id uuid,variant_id uuid,direction text,started_at timestamptz,ended_at timestamptz,plan_revision int);
 CREATE TABLE stops(id uuid,name text,latitude float8,longitude float8,sequence int);
 CREATE TABLE route_checkpoints(id uuid,stop_id uuid,variant_id uuid,name text,radius_meters int,tolerance_minutes int,target_minutes int);
 CREATE TABLE driver_checkins(id uuid DEFAULT gen_random_uuid(),run_id uuid,session_id uuid,checkpoint_id uuid,sequence int,name text,latitude float8,longitude float8,progress_meters float8,radius_meters int,tolerance_minutes int,expected_at timestamptz);
 CREATE TABLE fleet_vehicles(id uuid,tracking_id text);
 CREATE TABLE driver_sessions(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,driver_id uuid,conductor_id uuid,vehicle_id uuid,bus_id text,route_id uuid,variant_id uuid,transport_line_id uuid,status text,started_at timestamptz DEFAULT now(),ended_at timestamptz);`);
 await pg.exec(readFileSync('src/db/migrations/025_driver_session_lifecycle.sql','utf8'));
 await pg.exec(readFileSync('src/db/migrations/025_driver_session_lifecycle.sql','utf8'));
 const driver='00000000-0000-4000-8000-000000000001';
 await pg.query("INSERT INTO users VALUES($1,'driver','active')",[driver]);
 const db=require('../dist/db'),original=db.getClient;
 db.getClient=async()=>({query:(...args)=>pg.query(...args),release(){}});t.after(()=>{db.getClient=original;});
 const {startSession,endSession,currentSession}=require('../dist/driver-sessions/driverSessions.service');
 const route='00000000-0000-4000-8000-000000000002',variant='00000000-0000-4000-8000-000000000003';
 await pg.query('INSERT INTO routes(id) VALUES($1)',[route]);
 await pg.query("INSERT INTO route_variants VALUES($1,$2,'ida','[[-116,31],[-116,31.02]]')",[variant,route]);
 await pg.query("INSERT INTO stops VALUES($1,'Control',31.01,-116,0)",[variant]);
 await pg.query("INSERT INTO route_checkpoints VALUES($1,$1,$1,'Control',50,2,15)",[variant]);
 const body={bus_id:'bus',route_id:route,variant_id:variant,request_id:'attempt-1'};
 const first=await startSession(driver,body);
 const controlBefore=(await pg.query('SELECT * FROM driver_checkins')).rows[0];
 const retry=await startSession(driver,body);
 const controlAfter=(await pg.query('SELECT * FROM driver_checkins')).rows;
 assert.equal(controlAfter.length,1);assert.equal(controlAfter[0].id,controlBefore.id);
 assert.equal(String(controlAfter[0].expected_at),String(controlBefore.expected_at));
 assert.equal(retry.id,first.id);assert.equal(String(retry.started_at),String(first.started_at));
 await assert.rejects(startSession(driver,{bus_id:'other',request_id:'attempt-1'}));
 await assert.rejects(startSession(driver,{bus_id:'bus',request_id:'attempt-2'}));
 await assert.rejects(startSession(driver,{bus_id:'bus'}),e=>e.statusCode===409);
 assert.equal((await pg.query('SELECT ended_at FROM driver_checkpoint_runs')).rows[0].ended_at,null);
 assert.equal((await pg.query('SELECT * FROM driver_sessions')).rows.length,1);
 const returning='00000000-0000-4000-8000-000000000005';
 await pg.query("INSERT INTO route_variants VALUES($1,$2,'vuelta','[[-116,31.02],[-116,31]]')",[returning,route]);
 await pg.query("UPDATE driver_checkpoint_runs SET variant_id=$1,direction='vuelta' WHERE session_id=$2",[returning,first.id]);
 const restored=await currentSession(driver);assert.equal(restored.variant_id,returning);assert.equal(restored.direction,'vuelta');
 assert.equal(String(restored.started_at),String(first.started_at));
 const ended=await endSession(driver,first.id);
 const again=await endSession(driver,first.id);
 assert.equal(String(ended.ended_at),String(again.ended_at));
 assert.ok((await pg.query('SELECT ended_at FROM driver_checkpoint_runs')).rows[0].ended_at);
 assert.equal(await currentSession(driver),null);
 await assert.rejects(endSession('00000000-0000-4000-8000-000000000002',first.id));
 assert.equal((await startSession(driver,body)).status,'ended');
 const next=await startSession(driver,{bus_id:'bus',request_id:'attempt-2'});
 assert.notEqual(next.id,first.id);
});
