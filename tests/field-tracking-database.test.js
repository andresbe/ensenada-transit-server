const {test}=require('node:test');const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');const {PGlite}=require('@electric-sql/pglite');
process.env.NODE_ENV='test';
test('persisted service rejects replay, survives direction recovery and isolates new sessions',async t=>{
 const pg=new PGlite();t.after(()=>pg.close());
 await pg.exec(`CREATE TABLE conductores(id uuid PRIMARY KEY,correo text);
 CREATE TABLE users(id uuid,role text,status text);
 CREATE TABLE routes(id uuid PRIMARY KEY,checkpoint_revision int DEFAULT 0);
 CREATE TABLE route_variants(id uuid PRIMARY KEY,route_id uuid,direction text,coordinates jsonb);
 CREATE TABLE driver_sessions(id uuid PRIMARY KEY,status text,bus_id text,route_id uuid,conductor_id uuid,driver_id uuid,variant_id uuid,started_at timestamptz,last_checkpoint_gps_at timestamptz,last_heartbeat_at timestamptz,last_gps_at timestamptz);
 CREATE TABLE driver_checkpoint_runs(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,session_id uuid,variant_id uuid,direction text,started_at timestamptz,ended_at timestamptz,plan_revision int);
 CREATE UNIQUE INDEX one_run ON driver_checkpoint_runs(session_id) WHERE ended_at IS NULL;
 CREATE TABLE stops(id uuid,name text,latitude float8,longitude float8,sequence int);
 CREATE TABLE route_checkpoints(id uuid,stop_id uuid,variant_id uuid,name text,radius_meters int,tolerance_minutes int,target_minutes int);
 CREATE TABLE driver_checkins(id uuid DEFAULT gen_random_uuid(),run_id uuid,session_id uuid,checkpoint_id uuid,sequence int,name text,latitude float8,longitude float8,progress_meters float8,radius_meters int,tolerance_minutes int,expected_at timestamptz,arrived_at timestamptz,received_at timestamptz,gps_accuracy float8);`);
 await pg.exec(readFileSync('src/db/migrations/024_driver_direction_evidence.sql','utf8'));
 const ids=Array.from({length:5},(_,i)=>`00000000-0000-4000-8000-00000000000${i}`);
 const [driver,route,ida,vuelta,session]=ids, now=Date.now();
 await pg.query('INSERT INTO conductores VALUES($1,$2)',[driver,'field@test.local']);
 await pg.query('INSERT INTO routes(id) VALUES($1)',[route]);
 for(const [id,direction,coordinates] of [[ida,'ida',[[-116,31],[-116,31.02]]],[vuelta,'vuelta',[[-116,31.02],[-116,31]]]])await pg.query('INSERT INTO route_variants VALUES($1,$2,$3,$4)',[id,route,direction,JSON.stringify(coordinates)]);
 await pg.query("INSERT INTO driver_sessions(id,status,bus_id,route_id,conductor_id,variant_id,started_at) VALUES($1,'active','bus',$2,$3,$4,$5)",[session,route,driver,ida,new Date(now-600000)]);
 const db=require('../dist/db');const original=db.getClient;
 db.getClient=async()=>({query:(...args)=>pg.query(...args),release(){}});t.after(()=>{db.getClient=original;});
 const {registerGpsCheckin}=require('../dist/driver-sessions/checkpoints.service');
 const sample={sessionId:session,sourceId:'field@test.local',sourceType:'driver',busId:'bus',routeId:route,routeVariantId:ida,routeVariantDirection:'ida',longitude:-116,accuracy:8,speed:10};
 const send=(latitude,timestamp,heading=180)=>registerGpsCheckin('field@test.local',{...sample,latitude,timestamp,heading});
 await send(31.019,now-70000,0);
 const run=(await pg.query('SELECT id FROM driver_checkpoint_runs')).rows[0].id;
 await pg.query("INSERT INTO driver_checkins(run_id,session_id,sequence,name,latitude,longitude,radius_meters,tolerance_minutes,expected_at) VALUES($1,$2,0,'Behind',31.001,-116,75,2,now()),($1,$2,1,'Ahead',31.014,-116,75,2,now())",[run,session]);
 await send(31.014,now-30000);
 const controls=(await pg.query('SELECT * FROM driver_checkins ORDER BY sequence')).rows;
 assert.equal(controls[0].arrived_at,null,'unobserved control is never invented');
 assert.ok(controls[1].arrived_at,'missed earlier control does not block observed later one');
 await send(31.013,now-15000);
 const last=await send(31.012,now);
 assert.equal(last.routeVariantId,vuelta);
 assert.equal((await pg.query('SELECT * FROM driver_checkpoint_runs')).rows.length,2);
 assert.equal((await send(31.019,now-70000,0)).timestamp,now,'old sample returns confirmed latest position');
 assert.equal((await send(31.015,now)).latitude,31.012,'same timestamp is idempotent');
 assert.equal((await pg.query('SELECT * FROM driver_checkpoint_runs')).rows.length,2,'replay does not restart clock');
 await assert.rejects(registerGpsCheckin('field@test.local',{...sample,sessionId:driver,latitude:31.012,timestamp:now+1}),e=>e.statusCode===409||e.status===409);
 await pg.query("UPDATE driver_sessions SET status='ended'");
 await assert.rejects(send(31.011,now+1));
});
